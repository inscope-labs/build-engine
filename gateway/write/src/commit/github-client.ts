/**
 * The GitHub client: one repository, one branch, and nothing else.
 *
 * The client is **fixed**. It reads the repository, the branch and the credential from the
 * configuration, and it has no parameter that a request could reach. There is no method that
 * creates a repository, creates a branch, creates a folder, merges, opens a pull request, pushes
 * anywhere else, deletes anything, or force-pushes. A commit is one commit, to one branch, on top
 * of one expected parent (protocol section 8.1).
 *
 * Three properties matter more than the API coverage:
 *
 *  - **Every call is bounded.** A provider that has not answered in the configured timeout is
 *    treated as a failure, not as a wait. An agent that is left hanging is an agent that will
 *    retry into a duplicate commit.
 *  - **The provider's answer never reaches the agent.** GitHub's status and body are turned into
 *    the gateway's own error codes at the edge of this module, and the body is never read. A
 *    provider error can quote the request, and the request can quote the agent's content.
 *  - **The error carries a kind, not a guess.** `timeout`, `network` and `status` are what the
 *    retry policy needs; the gateway code is chosen further in, where the call's purpose is known.
 *    A missing *branch* and a missing *file* are the same status and different problems.
 */
import { GITHUB_STATUS } from "../types/github.ts";

/** Why a provider call failed. */
export type ProviderFailureKind = "timeout" | "network" | "status";

/**
 * A provider call that failed.
 *
 * The message is for the gateway's own log. It names the status and never the body, the URL or
 * the credential.
 */
export class ProviderError extends Error {
  /** Why it failed. */
  readonly kind: ProviderFailureKind;
  /** The provider's status, when it answered at all. */
  readonly status: number | null;

  constructor(kind: ProviderFailureKind, status: number | null, message: string) {
    super(message);
    this.name = "ProviderError";
    this.kind = kind;
    this.status = status;
  }
}

/** How the client is configured. */
export interface GitHubClientOptions {
  /** `owner/name` of the submissions repository. */
  repo: string;
  /** The branch. The only branch this client can reach. */
  branch: string;
  /** The credential. A secret. */
  token: string;
  /** The API base URL. */
  apiBase: string;
  /** The per-call timeout, in milliseconds. */
  timeoutMs: number;
  /** The user agent the gateway identifies itself with. */
  userAgent: string;
  /** The fetch implementation. The tests replace it; production does not. */
  fetchImpl?: typeof fetch;
}

/** One entry of a tree. */
export interface TreeEntry {
  path: string;
  mode: string;
  type: string;
  sha: string;
}

/** The commit the gateway creates. */
export interface CommitRequest {
  /** The tree the commit points at. */
  tree: string;
  /** The parents. Exactly one: the expected head. */
  parents: string[];
  /** The message. Generated by the gateway, never by a request. */
  message: string;
  /** The author and committer date, in ISO 8601. */
  date: string;
  /** The author name. */
  authorName: string;
  /** The author email. */
  authorEmail: string;
}

export class GitHubClient {
  private readonly repo: string;
  private readonly branch: string;
  private readonly token: string;
  private readonly apiBase: string;
  private readonly timeoutMs: number;
  private readonly userAgent: string;
  private readonly fetchImpl: typeof fetch;

  constructor(options: GitHubClientOptions) {
    this.repo = options.repo;
    this.branch = options.branch;
    this.token = options.token;
    this.apiBase = options.apiBase.replace(/\/+$/, "");
    this.timeoutMs = options.timeoutMs;
    this.userAgent = options.userAgent;
    // The fetch implementation is **bound to the global scope**, and that is not a detail.
    //
    // The Workers runtime's `fetch` refuses to be called with the wrong receiver:
    //
    //     TypeError: Illegal invocation: function called with incorrect `this` reference.
    //
    // `this.fetchImpl(url, init)` is a method call on this client, so the receiver would be the
    // client, and every provider call would fail with a TypeError that the catch below turns
    // into a "network" failure: `provider-unavailable`, for ever. The gateway would never have
    // spoken to GitHub at all, and the failure would have looked like a provider outage.
    //
    // The test suite never saw it, because the tests replace the implementation with a mock that
    // does not care who calls it. This was F0-072, and the rehearsal against the real provider
    // in Stage 6.1 is what found it.
    this.fetchImpl = (options.fetchImpl ?? globalThis.fetch).bind(globalThis);
  }

  /**
   * The sha the branch currently points at.
   *
   * A 404 here means the configured branch does not exist, which is a configuration fault and not
   * a conflict. The caller decides that; this method only reports the status.
   */
  async getBranchHead(): Promise<string> {
    const data = (await this.request("GET", `/git/ref/heads/${branchPath(this.branch)}`)) as {
      object: { sha: string };
    };
    return data.object.sha;
  }

  /** A commit: its tree, its parents and its message. */
  async getCommit(sha: string): Promise<{ sha: string; treeSha: string; parents: string[]; message: string }> {
    const data = (await this.request("GET", `/git/commits/${encodeURIComponent(sha)}`)) as {
      sha: string;
      tree: { sha: string };
      parents: { sha: string }[];
      message: string;
    };
    return {
      sha: data.sha,
      treeSha: data.tree.sha,
      parents: data.parents.map((parent) => parent.sha),
      message: data.message,
    };
  }

  /** One level of a tree. */
  async getTree(sha: string): Promise<{ sha: string; entries: TreeEntry[] }> {
    const data = (await this.request("GET", `/git/trees/${encodeURIComponent(sha)}`)) as {
      sha: string;
      tree: TreeEntry[];
    };
    return { sha: data.sha, entries: data.tree ?? [] };
  }

  /**
   * A blob: the content, addressed by its own hash.
   *
   * The content is text, because the gateway is a text protocol, and it is sent as UTF-8 rather
   * than base64 — the same bytes either way, and one less encoding to get wrong.
   */
  async createBlob(content: string): Promise<string> {
    const data = (await this.request("POST", "/git/blobs", { content, encoding: "utf-8" })) as {
      sha: string;
    };
    return data.sha;
  }

  /**
   * A tree, on top of a base tree.
   *
   * The base tree is the expected head's tree, so that everything already in the repository is
   * carried over untouched. The entries are the selected files, at their paths inside the task
   * folder.
   */
  async createTree(baseTree: string, entries: TreeEntry[]): Promise<string> {
    const data = (await this.request("POST", "/git/trees", { base_tree: baseTree, tree: entries })) as {
      sha: string;
    };
    return data.sha;
  }

  /**
   * A commit object.
   *
   * The commit is **not** pushed to the branch by this call. It creates the object; moving the
   * branch is a separate, guarded step, and the separation is what makes the timeout case
   * recoverable.
   */
  async createCommit(input: CommitRequest): Promise<string> {
    const identity = { name: input.authorName, email: input.authorEmail, date: input.date };
    const data = (await this.request("POST", "/git/commits", {
      tree: input.tree,
      parents: input.parents,
      message: input.message,
      author: identity,
      committer: identity,
    })) as { sha: string };
    return data.sha;
  }

  /**
   * Move the branch to a commit.
   *
   * `force` is false and is not a parameter: a commit that is not a fast-forward from the
   * branch's current head is refused by the provider, which is the second line of defence behind
   * the gateway's own expected-head check.
   */
  async updateRef(sha: string): Promise<void> {
    await this.request("PATCH", `/git/refs/heads/${branchPath(this.branch)}`, { sha, force: false });
  }

  /**
   * One HTTP call.
   *
   * The timeout is enforced with an abort signal, so that a provider that accepts the connection
   * and then says nothing cannot hold the call open.
   */
  private async request(method: string, path: string, body?: unknown): Promise<unknown> {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), this.timeoutMs);
    let response: Response;
    try {
      const headers: Record<string, string> = {
        Authorization: `Bearer ${this.token}`,
        Accept: "application/vnd.github+json",
        "X-GitHub-Api-Version": "2022-11-28",
        "User-Agent": this.userAgent,
      };
      if (body !== undefined) headers["Content-Type"] = "application/json";
      response = await this.fetchImpl(`${this.apiBase}/repos/${this.repo}${path}`, {
        method,
        headers,
        body: body !== undefined ? JSON.stringify(body) : undefined,
        signal: controller.signal,
      });
    } catch (e) {
      if (isAbort(e)) {
        throw new ProviderError("timeout", null, `the provider call timed out after ${this.timeoutMs}ms`);
      }
      throw new ProviderError("network", null, "the provider call failed");
    } finally {
      clearTimeout(timer);
    }

    if (!response.ok) {
      // The body is deliberately not read. A provider error can quote the request, and the
      // request quotes the agent's content.
      throw new ProviderError("status", response.status, `the provider answered ${response.status}`);
    }
    if (response.status === GITHUB_STATUS.noContent) return null;
    return response.json();
  }
}

/**
 * The path of a branch.
 *
 * A branch name may contain a slash, and GitHub's reference API wants the slashes. Each segment
 * is encoded on its own, so that a branch called `feature/a b` is `feature/a%20b` and not
 * `feature%2Fa%20b`.
 */
function branchPath(branch: string): string {
  return branch.split("/").map((segment) => encodeURIComponent(segment)).join("/");
}

/** Whether an error is an abort. */
function isAbort(e: unknown): boolean {
  return e instanceof Error && (e.name === "AbortError" || e.name === "TimeoutError");
}
